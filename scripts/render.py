def roman_list(names, prefix):
    return ", ".join(n.replace(prefix, "") for n in sorted(names, key=lambda s: int(re.sub(r"\D", "", s) or 0)))


def definition_list(names, book):
    """Book I's definitions a proof rests on (`Definition15`). Definitions are numbered
    book by book, so each keeps its book, as a table writes it (STYLE §4): "Def. I.15"
    on a page of every book, Book I's included."""
    nums = roman_list(names, "Definition")
    if not nums:
        return nums
    return ", ".join(f"Def. I.{n}" for n in nums.split(", "))


def prop_key(ref):
    """Sort references by book, then by number: I.3 before I.10, and I.47 before II.4."""
    return heath.prop_key(ref)


def prop_link(ref, book):
    """A link to a proposition's page, from a page of `book`; a porism links to its
    anchor on its proposition's page, "[III.1 Por.](01.md#porism)", and a companion to
    its own, "[I.40 general](40.md#general)"."""
    r = heath.parse_ref(ref)
    where = "" if r.book == book else f"../{r.book}/"
    anchor = {"porism": "#porism", "companion": f"#{r.name}"}.get(r.kind, "")
    return f"[{r}]({where}{r.n:02d}.md{anchor})"


# A proposition in one of Heath's brackets, or its porism: "I. 4", "III. 1, Por.".
BRACKETED_PROP = re.compile(r"([IVX]+)\.\s*(\d+)(,\s*Por\.)?")


def heath_refs(paragraphs, book=None):
    """Heath's references: what his translation gives in square brackets, in four
    groups, propositions, postulates, definitions and common notions, each sorted by
    number (I.3 before I.10). They are Heath's editorial references, not Euclid's words
    ("Such specific quotations of earlier propositions are rare in Euclid", vol. 1,
    p. 83), and an absent bracket does not mean Euclid gave no reason.

    A porism keeps its own reference: "[III. 1, Por.]" is III.1 Por. A definition keeps
    its book, as our prose and tables write it (STYLE §4), since Books II and III have
    their own: "Def. III.11", "Def. I.10", and on a page of Book I, "Def. I.15" for
    Heath's bare "[Def. 15]"."""
    groups = {"props": [], "Post.": [], "Def.": [], "C.N.": []}
    for j in heath.justifications(paragraphs):
        kind, num = j.rsplit(" ", 1)
        if kind == "Def." and book:
            # A bare "Def. 15" is the book's own definition: Def. I.15 in Book I.
            groups["Def."].append(f"{book}.{num}")
        elif kind in ("Post.", "Def.", "C.N."):
            groups[kind].append(int(num))
        elif kind.endswith(" Def."):
            # "III. Def. 11" is Def. III.11, and "I. Def. 15" in a later book Def. I.15.
            groups["Def."].append(f"{kind.split('.')[0]}.{num}")
    # heath.justifications counts a porism as its proposition; here each keeps its own.
    for p in paragraphs:
        for inner in heath.CITATION.findall(p):
            for part in re.split(r";|\band\b", inner):
                m = BRACKETED_PROP.fullmatch(" ".join(part.split()))
                if m:
                    ref = f"{m.group(1)}.{int(m.group(2))}" + (" Por." if m.group(3) else "")
                    if ref not in groups["props"]:
                        groups["props"].append(ref)
    groups["props"].sort(key=prop_key)
    for kind in ("Post.", "Def.", "C.N."):
        # Duplicates dropped; the page's own book first (Def. II.1), then another's
        # (Def. I.15).
        groups[kind] = sorted(set(groups[kind]), key=lambda d: (0, (d, ())) if isinstance(
            d, int) else (0 if d.split(".")[0] == book else 1, prop_key(d)))
    return groups


def heath_refs_text(groups, book):
    """Heath's references for a page, grouped as he writes them: "I.3, I.4; Post. 1, 2"."""
    parts = [", ".join(prop_link(c, book) for c in groups["props"])]
    parts += [f"{kind} " + ", ".join(map(str, groups[kind]))
              for kind in ("Post.", "Def.", "C.N.") if groups[kind]]
    return "; ".join(x for x in parts if x)


def split_porism(book, n):
    """Heath's text of a proposition in two: the enunciation and proof without the
    porism, and the porism paragraph alone ([] when there is none). Each part's
    references go in its own column of the page's table."""
    _, enunciation, proof = heath.read(book, n)
    own = [enunciation] + [q for q in proof if not heath.PORISM.match(q)]
    return own, [q for q in proof if heath.PORISM.match(q)]


HEATH_TITLE = "The Thirteen Books of Euclid's Elements"


# The Internet Archive scans of Heath's volumes: vol. 1 (Books I–II), vol. 2 (Books III–IX).
# A source comment naming a volume not here keeps its leaves as plain text.
SCANS = {"1": "thirteenbookseu02heibgoog", "2": "thirteenbookseu00heibgoog"}
ARCHIVE = "https://archive.org/details/"


def scan_url(vol, leaf):
    """The Internet Archive's page for one leaf of Heath's scan: `scan_url("1", "n261")`
    is the leaf of vol. 1 that holds p. 241. A source comment numbers its leaves as the
    Archive does, so the leaf goes into the address as it stands."""
    return f"{ARCHIVE}{SCANS[vol]}/page/{leaf}"


def scan_volume(source):
    """The volume a source comment names ("vol. 2" gives "2"), or None if it names none
    whose scan is in SCANS."""
    vol = re.search(r"vol\. (\d+)", source)
    return vol.group(1) if vol and vol.group(1) in SCANS else None


def leaf_links(leaves, vol):
    """Leaves as links, joined as prose: "[n67](…) and [n68](…)"."""
    links = [f"[{leaf}]({scan_url(vol, leaf)})" for leaf in leaves]
    return links[0] if len(links) == 1 else ", ".join(links[:-1]) + " and " + links[-1]


# What a source comment says of the scan: "scan leaves n261–n262", "scan leaf n390",
# "figure on n261", "figures on n86", "figures on n67 and n68", "figures on n79, n80 and n81".
SCAN_LEAVES = re.compile(r"scan leaves (n\d+)[–-](n\d+)|scan leaf (n\d+)"
                         r"|(figures?) on (n\d+(?:(?:, | and )n\d+)*)")
SCAN_ID = re.compile(r"(Internet Archive scan )([A-Za-z0-9_.-]*[A-Za-z0-9_])")


def link_scans(source):
    """A source comment with what it says of the scan linked to the Internet Archive:
    "scan leaves n261–n262" to the first of them, "scan leaf n390" and "figure on n261"
    to theirs, each leaf of "figures on n67 and n68" to its own, and the scan's
    identifier, which the front pages name, to the scan itself."""
    vol = scan_volume(source)

    def leaves(m):
        first, last, one, figures, on = m.groups()
        if first:
            return f"[scan leaves {first}–{last}]({scan_url(vol, first)})"
        if one:
            return f"[scan leaf {one}]({scan_url(vol, one)})"
        found = re.findall(r"n\d+", on)
        if len(found) == 1:
            return f"[{figures} on {found[0]}]({scan_url(vol, found[0])})"
        return f"{figures} on {leaf_links(found, vol)}"

    if vol:
        source = SCAN_LEAVES.sub(leaves, source)
    return SCAN_ID.sub(lambda m: f"{m.group(1)}[{m.group(2)}]({ARCHIVE}{m.group(2)})", source)


def euclids_text(source):
    """The footer naming Heath's pages, his title in italics, and the scan linked (see
    link_scans). The source comment starts with "Source:"."""
    source = re.sub(r"^Source:\s*", "", source).replace(HEATH_TITLE, f"*{HEATH_TITLE}*")
    return f"<sub>Euclid's text: {link_scans(source)}</sub>"


def heath_figure_note(source):
    """For a proposition whose lettered figure is still to be drawn: where Heath's own is,
    read from the source comment ("vol. 2 … figure on n18", "figures on n67 and n68")."""
    vol = scan_volume(source)
    leaves = re.search(r"figures? on (n\d+(?:(?:, | and )n\d+)*)", source)
    if not vol or not leaves:
        return "_Euclid's figure, with Heath's letters, is still to be drawn._"
    found = re.findall(r"n\d+", leaves.group(1))
    if len(found) == 1:
        where = f"[scan leaf {found[0]}]({scan_url(vol, found[0])})"
    else:
        where = "scan leaves " + leaf_links(found, vol)
    if leaves.group(0).startswith("figures"):
        # Heath draws more than one figure (III.25, III.33, III.35, III.36).
        return ("_Euclid's figures, with Heath's letters, are still to be drawn; until then, "
                f"Heath's own are on {where}._")
    return ("_Euclid's figure, with Heath's letters, is still to be drawn; until then, "
            f"Heath's own is on {where}._")


def figure_note(record):
    """What the page says under Euclid's figure (docs/STYLE.md, section 7), from the review
    record's `[figure]`, whose keys review/SCHEMA.md defines: its `case`, as "Drawn for one
    case: D between C and B, as in Heath's figure." (one full stop, whether or not the case
    ends with its own), then its `note`. Nothing when the record gives neither."""
    figure = (record or {}).get("figure") or {}
    said = ([f"Drawn for one case: {figure['case'].rstrip('.')}."] if figure.get("case")
            else [])
    return " ".join(said + ([figure["note"]] if figure.get("note") else []))


