def load_facts():
    path = ROOT / "facts.json"
    if not path.exists():
        return {}
    return {p["ref"]: p for p in json.loads(path.read_text())["propositions"]}


def load_axiom_docs():
    """name -> (first sentence of docstring, path, line) for every axiom."""
    docs = {}
    pattern = re.compile(r"/--((?:(?!-/).)*?)-/\s*axiom\s+([^\s({]+)", re.S)
    for path in sorted((ROOT / "Elements" / "Foundations").rglob("*.lean")):
        src = path.read_text()
        # facts.json names an axiom by its namespace below `Elements`, e.g.
        # `Tacit.circles_meet` or, for a Euclidean-only rule, `Tacit.Euclidean.…`.
        ns = re.search(r"^namespace Elements\.(\S+)", src, re.M)
        prefix = ns.group(1) + "." if ns else ""
        for m in pattern.finditer(src):
            doc = " ".join(m.group(1).split())
            line = src[: m.start(2)].count("\n") + 1
            docs[prefix + m.group(2)] = (doc, path.relative_to(ROOT).as_posix(), line)
    return docs


def svg_desc(path):
    """The one-line caption kept in an SVG's <desc> element."""
    m = re.search(r"<desc>(.*?)</desc>", path.read_text(), re.S)
    return " ".join(m.group(1).split()) if m else ""


def lean_body(path):
    """The part of a proposition file worth showing: from `open Tacit` to the end."""
    src = path.read_text()
    start = src.find("open Tacit")
    end = src.rfind("end Elements.Book")
    body = src[start + len("open Tacit"):end] if start >= 0 else src
    return body.strip("\n")


def group_axioms(names):
    groups = {"Postulates": [], "Definitions": [], "Superposition": [],
              "Reading the figure": [], "Lengths, angles and areas": [],
              "Laws of magnitude": []}
    for n in names:
        if n.startswith("Postulate"):
            groups["Postulates"].append(n)
        elif n.startswith("Definition"):
            groups["Definitions"].append(n)
        elif n == "Tacit.superposition":
            groups["Superposition"].append(n)
        else:
            groups["_tacit"] = groups.get("_tacit", []) + [n]
    return groups


def axiom_kind(path: str) -> str:
    if path.endswith("Tacit/Magnitudes.lean"):
        return "Laws of magnitude"
    if path.endswith(("Tacit/Constructions.lean", "Tacit/Diagram.lean")):
        return "Reading the figure"
    if path.endswith(("Tacit/Metric.lean", "Tacit/Transfer.lean")):
        return "Lengths, angles and areas"
    if path.endswith("Tacit/Superposition.lean"):
        return "Superposition"
    return "Other"


def roman_list(names, prefix):
    return ", ".join(n.replace(prefix, "") for n in sorted(names, key=lambda s: int(re.sub(r"\D", "", s) or 0)))


def prop_key(ref):
    """Sort references by book, then by number: I.3 before I.10, and I.47 before II.4."""
    return heath.prop_key(ref)


def prop_link(ref, book):
    """A link to a proposition's page, from a page of `book`."""
    b, num = ref.split(".")
    where = "" if b == book else f"../{b}/"
    return f"[{ref}]({where}{int(num):02d}.md)"


def euclid_cites(paragraphs):
    """What Euclid gives in brackets, in four groups: propositions, postulates,
    definitions and common notions, each sorted by number (I.3 before I.10)."""
    groups = {"props": [], "Post.": [], "Def.": [], "C.N.": []}
    for j in heath.justifications(paragraphs):
        kind, num = j.rsplit(" ", 1)
        if kind in ("Post.", "Def.", "C.N."):
            groups[kind].append(int(num))
        else:
            groups["props"].append(f"{kind}{num}")  # "I. 4", or "V. 9" in a later book
    groups["props"].sort(key=prop_key)
    for kind in ("Post.", "Def.", "C.N."):
        groups[kind].sort()
    return groups


def euclid_cites_text(groups, book):
    """Euclid's brackets for a page, grouped as Heath writes them: "I.3, I.4; Post. 1, 2"."""
    parts = [", ".join(prop_link(c, book) for c in groups["props"])]
    parts += [f"{kind} " + ", ".join(map(str, groups[kind]))
              for kind in ("Post.", "Def.", "C.N.") if groups[kind]]
    return "; ".join(x for x in parts if x)


def euclids_text(source):
    """The footer naming Heath's pages. The source comment starts with "Source:"."""
    source = re.sub(r"^Source:\s*", "", source)
    return f"<sub>Euclid's text: {source}</sub>"


TACIT_CREDIT = ("<sub>The tacit rules follow the System E of Jeremy Avigad, Edward Dean and "
                "John Mumma, read alongside LeanEuclid (Logan Murphy, Kaiyu Yang, Jialiang Sun, "
                "Zhaoyu Li, Anima Anandkumar and Xujie Si).</sub>")


def rests_on(p, docs, depth, book, euclid):
    """Markdown for the 'What it rests on' section. `euclid` is what Euclid cites
    (see euclid_cites); it comes from the text, so it is shown before the Lean is done."""
    up = "../" * depth
    lines = ["| | |", "|---|---|",
             "| Euclid cites | " + (euclid_cites_text(euclid, book) or "none") + " |"]
    if not p or p["status"] == "sketched":
        return ("\n".join(lines) + "\n\n_Not yet proved in Lean, so what the Lean rests on "
                "is not yet known._\n")
    axioms = p["axioms"]
    posts = [a for a in axioms if a.startswith("Postulate")]
    defs = [a for a in axioms if a.startswith("Definition")]
    tacit = [a for a in axioms if a.startswith("Tacit.")]
    lines.append("| Lean cites | " + (", ".join(prop_link(c, book) for c in
                 sorted(p["cites"], key=prop_key)) or "no propositions") + " |")
    lines.append("| Postulates | " + (roman_list(posts, "Postulate") or "none") + " |")
    lines.append("| Definitions | " + (roman_list(defs, "Definition") or "none") + " |")
    lines.append("| Common Notions | " + (", ".join(c.replace("C.N. ", "") for c in
                 sorted(set(p["common_notions"]))) or "none") + " |")
    lines.append(f"| Tacit assumptions | {len(tacit)} (listed below) |")
    out = "\n".join(lines) + "\n"
    if p["status"] == "proved-pending":
        out += ("\n_This proof is complete, but it cites propositions that are still "
                "sketched, so the list above will grow when they are proved._\n")
    if tacit:
        by_kind = {}
        for a in tacit:
            doc, path, line = docs.get(a, ("", "", 0))
            by_kind.setdefault(axiom_kind(path), []).append((a, doc, path, line))
        out += f"\n<details><summary>The {len(tacit)} things Euclid takes for granted here</summary>\n\n"
        for kind in ["Reading the figure", "Lengths, angles and areas", "Superposition",
                     "Laws of magnitude", "Other"]:
            if kind not in by_kind:
                continue
            out += f"**{kind}**\n\n"
            for a, doc, path, line in sorted(by_kind[kind]):
                out += f"- [`{a.replace('Tacit.', '')}`]({up}{path}#L{line}): {doc}\n"
            out += "\n"
        out += "</details>\n"
    return out


def page(book, n, count, titles, facts, docs):
    source, enunciation, proof = heath.read(book, n)
    # The enunciation counts too: I.22's [I. 20] is there.
    euclid = euclid_cites([enunciation] + proof)
    ref = f"{book}.{n}"
    p = facts.get(ref)
    status = STATUS.get(p["status"], "") if p else STATUS["sketched"]
    prev_link = f"[← {book}.{n - 1}]({n - 1:02d}.md)" if n > 1 else ""
    next_link = f"[{book}.{n + 1} →]({n + 1:02d}.md)" if n < count else ""
    nav = " · ".join(x for x in [f"[Book {book}](index.md)", prev_link, next_link] if x)
    figure = ROOT / "figures" / book / f"{n:02d}.svg"
    mishnah = ROOT / "mishnah" / book / f"{n:02d}.md"
    lean_path = ROOT / "Elements" / f"Book{book}" / f"Prop{n:02d}.lean"
    idea = ROOT / "figures" / book / f"{n:02d}-idea.svg"
    out = [GENERATED, nav, "", f"# Book {book}, Proposition {n}", "",
           f"*{titles[n]}*", "", f"> {enunciation}", ""]
    if idea.exists():
        caption = svg_desc(idea)
        out += [f"<p align=\"center\"><img src=\"../../figures/{book}/{n:02d}-idea.svg\" "
                f"alt=\"{caption}\" width=\"420\"></p>", "",
                f"<p align=\"center\"><em>{caption}</em></p>", ""]
    out += ["## Euclid's proof", ""]
    if figure.exists():
        out += [f"<p align=\"center\"><img src=\"../../figures/{book}/{n:02d}.svg\" "
                f"alt=\"Euclid's figure for Proposition {ref}, with Heath's letters\" width=\"360\"></p>", ""]
    for para in proof:
        out += [para, ""]
    out += ["## In Lean", "", status, "",
            f"From [`Elements/Book{book}/Prop{n:02d}.lean`](../../Elements/Book{book}/Prop{n:02d}.lean). "
            "Euclid's sentences are the `--` comments; the lines under each one are the Lean "
            "that carries it out.", "", "```lean", lean_body(lean_path), "```", "",
            "## What it rests on", "", rests_on(p, docs, 2, book, euclid)]
    out += ["## Mishnah", ""]
    if mishnah.exists():
        out += [mishnah.read_text().strip(), ""]
    else:
        out += ["_Commentary to come._", ""]
    out += ["---", "", euclids_text(source), "", TACIT_CREDIT, ""]
    return "\n".join(out)


def front_sections(book):
    """The headings of a book's front matter, in order: Book I has Definitions,
    Postulates and Common Notions; Book II has Definitions alone."""
    text = heath.HTML_COMMENT.sub("", (ROOT / "heath" / book / "front.md").read_text())
    return [line[3:].strip() for line in text.splitlines() if line.startswith("## ")]


def in_words(names):
    """["Definitions", "Postulates", "Common Notions"] ↦ "definitions, postulates and
    common notions"."""
    names = [n.lower() for n in names]
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def index(book, count, titles, facts):
    proved = sum(1 for n in range(1, count + 1)
                 if facts.get(f"{book}.{n}", {}).get("status") == "proved")
    start = f"Start with the [{in_words(front_sections(book))}](front.md)."
    if (ROOT / "docs" / "reports" / f"gaps-book-{book}.md").exists():
        start += (" What Euclid takes for granted along the way is gathered in "
                  f"[a catalogue](../../docs/reports/gaps-book-{book}.md).")
    out = [GENERATED, f"# Book {book}", "",
           f"**{proved} of {count} propositions proved in Lean.** "
           "✅ proved · ☑️ proved, citing propositions still to be proved · 🚧 sketched", "",
           start, "",
           "| | Proposition | |", "|---|---|---|"]
    for n in range(1, count + 1):
        st = facts.get(f"{book}.{n}", {}).get("status", "sketched")
        _, enunciation, _ = heath.read(book, n)
        short = enunciation if len(enunciation) < 110 else enunciation[:107].rsplit(" ", 1)[0] + "…"
        out.append(f"| {STATUS_SHORT[st]} | [{book}.{n}]({n:02d}.md) **{titles[n]}** | {short} |")
    return "\n".join(out) + "\n"


