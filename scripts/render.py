def use_self_check():
    """USE_CASES, read from USE_FILES, and ORDER_CASES; returns the number of cases and
    the faults."""
    code = {path: check_fidelity.without_comments(src) for path, src in USE_FILES.items()}
    declared = declared_names(code)
    own = next(iter(USE_FILES))
    faults = []
    for name, want in USE_CASES:
        got = use_kind(name, own, code, declared)
        if got != want:
            faults.append(f"{name} read as {got!r}, not {want!r}")
    for order, want in ORDER_CASES:
        got = re.findall(r"`Prop45\.(\w+)`", proof_cell({"status": "proved"},
                                                       ORDER_ATTACHED, order))
        if got != want:
            faults.append(f"the companions of {order!r} named as {got!r}, not {want!r}")
    return len(USE_CASES) + len(ORDER_CASES), faults


def lean_listing(book, n, facts):
    """The Lean of a page: the main theorem open; the lemmas before it folded in one
    <details>, with their names and line count; and the porism, companions and other
    declarations after it folded in another, those that later propositions use named apart
    from the lemmas only this proposition's own proofs use and from those nothing uses,
    which stand beside it (`use_kind`)."""
    parts = lean_parts(book, n)
    companions = {f"Prop{n}.{heath.parse_ref(a).name}"
                  for a in facts.get(f"{book}.{n}", {}).get("attached", [])
                  if heath.parse_ref(a).kind == "companion"}

    def names(found):
        return and_list([f"<code>{x}</code>" for x in found])

    def lines(text):
        k = text.count("\n") + 1
        return f"{k} line" + ("" if k == 1 else "s")

    def fold(summary, text):
        return [f"<details><summary>{summary}</summary>", "", "```lean", text, "```", "",
                "</details>", ""]

    out = []
    if parts.before:
        k = len(parts.before_names)
        what = f"{number_word(k)} lemma" + ("" if k == 1 else "s")
        out += fold(f"Before the theorem, {what}: {names(parts.before_names)} "
                    f"({lines(parts.before)})", parts.before)
    out += ["```lean", parts.main, "```", ""]
    if parts.after:
        porism = [x for x in parts.after_names if x == f"Prop{n}.porism"]
        comp = [x for x in parts.after_names if x in companions]
        rest = [x for x in parts.after_names if x not in porism + comp]
        own = heath.lean_path(book, n)
        kind = {x: use_kind(x, own, lean_code(), lean_declared()) for x in rest}
        later = [x for x in rest if kind[x] == "later"]
        local = [x for x in rest if kind[x] == "own"]
        beside = [x for x in rest if kind[x] == "beside"]
        what = []   # (a clause, the number of names it lists)
        if porism:
            what.append((f"its porism, {names(porism)}", len(porism)))
        if comp:
            what.append((f"its companion{'s' if len(comp) > 1 else ''}, {names(comp)}",
                         len(comp)))
        if later:
            k = len(later)
            more = "more " if porism or comp else ""
            what.append((f"{number_word(k)} {more}theorem{'s' if k > 1 else ''} "
                         f"later propositions use, {names(later)}", k))
        if local:
            k = len(local)
            what.append((f"{number_word(k)} lemma{'s' if k > 1 else ''} for its own "
                         f"proofs, {names(local)}", k))
        if beside:
            k = len(beside)
            what.append((f"{number_word(k)} lemma{'s' if k > 1 else ''} beside the "
                         f"proposition, {names(beside)}", k))
        anchors = "".join(f'<a name="{x.split(".", 1)[1]}"></a>' for x in comp)
        if anchors:
            out += [anchors, ""]
        clauses = [w for w, _ in what]
        if len(what) > 1 and any(k > 1 for _, k in what):
            summary = "; ".join(clauses[:-1]) + "; and " + clauses[-1]
        else:
            summary = and_list(clauses) if clauses else "more Lean"
        out += fold(f"After the theorem, {summary} ({lines(parts.after)})", parts.after)
    return "\n".join(out).rstrip("\n")


def page_nav(book, n, count):
    """The navigation line: the book's index, the previous and the next proposition.
    Across books, I.48 leads on to II.1, and II.1 back to I.48."""
    prev_link = f"[← {book}.{n - 1}]({n - 1:02d}.md)" if n > 1 else ""
    next_link = f"[{book}.{n + 1} →]({n + 1:02d}.md)" if n < count else ""
    order = list(BOOKS)
    i = order.index(book)
    if n == 1 and i > 0:
        before = order[i - 1]
        last = BOOKS[before][0]
        prev_link = f"[← {before}.{last}](../{before}/{last:02d}.md)"
    if n == count and i + 1 < len(order):
        after = order[i + 1]
        next_link = f"[{after}.1 →](../{after}/01.md)"
    return " · ".join(x for x in [f"[Book {book}](index.md)", prev_link, next_link] if x)


# The line under the heading "Mishnah", for a reader who meets the word on this page.
MISHNAH_LEAD = ("_Our commentary: what Euclid assumes, what Lean made us say out loud, and "
                "how the result looks by modern means._")

JUMP_LINKS = ("[Euclid's proof](#euclids-proof) · [In Lean](#in-lean) · "
              "[What it rests on](#what-it-rests-on) · [Mishnah](#mishnah)")


def page(book, n, count, titles, facts, docs, records):
    source, enunciation, proof = heath.read(book, n)
    # The enunciation counts too: I.22's [I. 20] is there. The porism's references go
    # in its own column.
    own, porism_text = split_porism(book, n)
    refs = heath_refs(own, book)
    ref = f"{book}.{n}"
    p = facts.get(ref)
    record = records.get(ref)
    attached = attached_entries(p, facts)
    attached_refs = [(a, heath_refs(porism_text, book) if a.get("kind") == "porism"
                      else heath_refs([], book)) for a in attached]
    nav = page_nav(book, n, count)
    figure = ROOT / "figures" / book / f"{n:02d}.svg"
    mishnah = ROOT / "mishnah" / book / f"{n:02d}.md"
    idea = ROOT / "figures" / book / f"{n:02d}-idea.svg"
    # A proposition Heath prints in square brackets (III.12) opens its bracket before
    # the enunciation, to close after "Q. E. D." at the end of the proof.
    opening = "[" if heath.bracketed(book, n) else ""
    out = [GENERATED, nav, "", f"# Book {book}, Proposition {n}", "",
           f"*{titles[n]}*", "", JUMP_LINKS, "", f"> {opening}{enunciation}", ""]
    if opening:
        out += [BRACKET_NOTES.get((book, n), BRACKET_DEFAULT), ""]
    out += [in_lean_line(p, record, book, n), ""]
    if idea.exists():
        caption = svg_desc(idea)
        alt = caption.replace('"', "&quot;")
        out += [f"<p align=\"center\"><img src=\"../../figures/{book}/{n:02d}-idea.svg\" "
                f"alt=\"{alt}\" width=\"420\"></p>", "",
                f"<p align=\"center\"><em>{caption}</em></p>", ""]
    out += ["## Euclid's proof", ""]
    if figure.exists():
        note = figure_note(record)
        alt = (f"Euclid's figure for Proposition {ref}, with Heath's letters" + (
            f". {note}" if note else "")).replace('"', "&quot;")
        out += [f"<p align=\"center\"><img src=\"../../figures/{book}/{n:02d}.svg\" "
                f"alt=\"{alt}\" width=\"360\"></p>", ""]
        if note:
            out += [f"<p align=\"center\"><em>{note}</em></p>", ""]
    else:
        out += [heath_figure_note(source), ""]
    for para in proof:
        # The porism's anchor, which its certificate row and its citations link to.
        out += [('<a name="porism"></a>' if heath.PORISM.match(para) else "") + para, ""]
    out += ["## In Lean", "", field_table(book, n, p, record, attached, docs), ""]
    cmap = clause_map(record)
    if cmap:
        out += [cmap, ""]
    out += [f"From [`Elements/Book{book}/Prop{n:02d}.lean`](../../Elements/Book{book}/Prop{n:02d}.lean). "
            + how_to_read(p, record, plain_text(proof)), ""]
    notes = passage_notes(record, plain_text(proof))
    if notes:
        out += [notes, ""]
    out += [lean_listing(book, n, facts), "",
            "## What it rests on", "", rests_on(p, docs, 2, book, refs, attached_refs)]
    out += ["## Mishnah", ""]
    if mishnah.exists():
        out += [MISHNAH_LEAD, "", generated_counts.without_markers(read_text(mishnah).strip()), ""]
    else:
        out += ["_Commentary to come._", ""]
    # A line or three from docs/reading.md, chosen for this proposition; no file, no section.
    reading = ROOT / "reading" / book / f"{n:02d}.md"
    further = generated_counts.without_markers(read_text(reading).strip()) if reading.exists() else ""
    if further:
        out += ["## Further reading", "", further, ""]
    out += [nav, ""]
    out += ["---", "", euclids_text(source), "", TACIT_CREDIT, ""]
    return "\n".join(out)


def front_sections(book):
    """The headings of a book's front matter, in order: Book I has Definitions,
    Postulates and Common Notions; Book II has Definitions alone."""
    text = heath.HTML_COMMENT.sub("", read_text(ROOT / "heath" / book / "front.md"))
    return [line[3:].strip() for line in text.splitlines() if line.startswith("## ")]


def in_words(names):
    """["Definitions", "Postulates", "Common Notions"] ↦ "definitions, postulates and
    common notions"."""
    names = [n.lower() for n in names]
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def book_intro(book):
    """A book's introduction, `mishnah/intro/<book>.md`, in the voice of the mishnah: what
    the book is about, and, once, what its pages share (the house words, the shared steps
    and where Postulate 5 comes in), so that no page has to say it again. Empty if the
    book has none yet."""
    path = ROOT / "mishnah" / "intro" / f"{book}.md"
    return generated_counts.without_markers(read_text(path).strip()) if path.exists() else ""


def ref_ranges(refs):
    """Propositions of one book in order, as our prose writes them: consecutive runs
    joined by an en dash (STYLE §5). ["I.1", …, "I.28", "I.31"] ↦ "I.1–I.28 and I.31"."""
    runs = []
    for r in refs:
        b, num = r.split(".")
        if runs and runs[-1][0] == b and runs[-1][2] == int(num) - 1:
            runs[-1][2] = int(num)
        else:
            runs.append([b, int(num), int(num)])
    return and_list([f"{b}.{lo}" if lo == hi else f"{b}.{lo}–{b}.{hi}" for b, lo, hi in runs])


def postulate5_sentence(book, facts, proved):
    """Where the parallel postulate comes into the book's proofs, from facts.json, in
    the certificate's words: what a proof uses, never what a proposition needs."""
    count = BOOKS[book][0]
    without = [r for r in proved if "Postulate5" not in facts[r]["axioms"]]
    using = [r for r in proved if r not in without]
    direct = [r for r in using if "Postulate5" in facts[r]["direct_axioms"]]
    # Where Heath's brackets first give Post. 5 in this book.
    heath_first = next((f"{book}.{n}" for n in range(1, count + 1)
                        if "Post. 5" in heath.justifications(sum(split_porism(book, n), []))),
                       None)
    if not using:
        return "None of the proofs uses the parallel postulate."
    if not without:
        if direct:
            where = ", where Euclid calls on it," if direct[0] == heath_first else ""
            rest = "the others through" if len(direct) == 1 else "the rest through"
            return (f"Every proof uses the parallel postulate: {and_list(direct)}'s directly"
                    f"{where} and {rest} the propositions they cite.")
        return "Every proof uses the parallel postulate, through the propositions it cites."
    first = using[0]
    just = ", just where Euclid first calls on it" if first == heath_first else ""
    return (f"Our proofs of {len(without)} propositions do not use the parallel postulate: "
            f"{ref_ranges(without)}. The first proof that does is {first}'s{just}.")


def overlap_sentences(overlap, facts, records, links, up):
    """What a book's summary says of the propositions an axiom already contains, or
    supplies a step of a proof of, told apart by the record's [overlap] `kind` and by
    whether the proof rests on that axiom (facts.json's `axioms`): "In III.2, III.5 and
    III.6 our tacit rules already contain the proposition…, and our proofs rest on them…";
    "In I.23 one of our tacit rules supplies a step of a proof of the proposition, and our
    proof rests on it"; "In I.7 one of our tacit rules supplies a step of a proof of the
    proposition, but our proof never uses that rule." Only a rule that states the
    proposition or gives it at once is said to contain it, as in the overlap catalogue.
    Where a proposition needs two rules together (III.6), it says so."""
    def rules(r):
        return overlap_rules(records[r]["overlap"])

    def together(rs):
        multi = [f"{r}, {number_word(len(rules(r)))} of them together" for r in rs
                 if len(rules(r)) > 1]
        return f" ({'; '.join('in ' + m for m in multi)})" if multi else ""

    family = ("tacit rules" if all(x.startswith("Tacit.") for r in overlap for x in rules(r))
              else "axioms")
    contain = [r for r in overlap if not overlap_steps(records[r]["overlap"])]
    step = [r for r in overlap if r not in contain]
    rests = [r for r in overlap if overlap_rests(facts.get(r), records[r]["overlap"])]
    out = []
    used = [r for r in contain if r in rests]
    if used:
        extra = together(used)
        if len(used) == 1 and not extra:
            out.append(f"In {links(used)} one of our {family} already contains the proposition, "
                       "and our proof rests on it, so the proof retraces Euclid's argument "
                       "within our rules and does not establish the rule.")
        else:
            out.append(f"In {and_list(links([r]) for r in used)} our {family} already contain "
                       f"the proposition{extra}, and our proofs rest on them, so each retraces "
                       "Euclid's argument within our rules and does not establish them.")
    unused = [r for r in contain if r not in rests]
    if unused:
        if len(unused) == 1:
            out.append(f"In {links(unused)} one of our {family} contains the proposition too, "
                       "but our proof never uses that rule.")
        else:
            out.append(f"In {and_list(links([r]) for r in unused)} our {family} contain the "
                       "propositions too, but our proofs never use those rules.")
    used = [r for r in step if r in rests]
    if used:
        extra = together(used)
        if len(used) == 1 and not extra:
            out.append(f"In {links(used)} one of our {family} supplies a step of a proof of "
                       "the proposition, and our proof rests on it.")
        else:
            out.append(f"In {and_list(links([r]) for r in used)} our {family} supply a step of "
                       f"a proof of each proposition{extra}, and our proofs rest on them.")
    unused = [r for r in step if r not in rests]
    if unused:
        extra = together(unused)
        if len(unused) == 1 and not extra:
            out.append(f"In {links(unused)} one of our {family} supplies a step of a proof "
                       "of the proposition, but our proof never uses that rule.")
        else:
            out.append(f"In {and_list(links([r]) for r in unused)} our {family} supply a step "
                       f"of a proof of each proposition{extra}, but our proofs never use those "
                       "rules.")
    out.append(f"[The overlap catalogue]({up}docs/reports/overlaps.md) gives each.")
    return " ".join(out)


def book_summary(book, facts, records, href, postulate5=True, up=""):
    """A book's completion summary, one line of Markdown generated from facts.json and
    the review records: how many propositions are proved, how many statements are
    whole, restricted or in part, whose argument the proofs follow, the propositions an
    axiom already contains or supplies a step of a proof of, and (unless `postulate5` is
    False) where the parallel postulate comes in. `href(ref)` is the link to a
    proposition's page. The same line heads the book's index, its section of
    CERTIFICATE.md and its row of README.md."""
    count = BOOKS[book][0]
    refs = [f"{book}.{n}" for n in range(1, count + 1)]

    def links(rs):
        return ", ".join(f"[{r}]({href(r)})" for r in rs)

    proved = [r for r in refs if facts.get(r, {}).get("status") == "proved"]
    head = (f"**All {count} propositions proved in Lean**" if len(proved) == count else
            f"**{len(proved)} of {count} propositions proved in Lean**")
    reviewed = [r for r in proved if records.get(r)]
    scope = {s: [r for r in reviewed if records[r]["statement"]["scope"] == s]
             for s in ("full", "restricted", "partial")}
    def states(k):
        return f"{k} as Euclid states {'it' if k == 1 else 'them'}"

    out = []
    if not reviewed:
        out.append(head + ".")
    elif not scope["restricted"] and not scope["partial"]:
        out.append(head + (", every one as Euclid states it." if len(reviewed) == len(proved)
                           else f": {states(len(scope['full']))}."))
    else:
        parts = [states(len(scope["full"]))] if scope["full"] else []
        if scope["restricted"]:
            parts.append(f"{len(scope['restricted'])} for a restricted statement "
                         f"({links(scope['restricted'])})")
        if scope["partial"]:
            parts.append(f"{len(scope['partial'])} in part, leaving clauses to Euclid's words "
                         f"({links(scope['partial'])})")
        out.append(f"{head}: {and_list(parts)}.")
    unreviewed = [r for r in proved if not records.get(r)]
    if unreviewed:
        out.append(f"Not yet reviewed against Euclid's enunciation: {links(unreviewed)}.")
    if reviewed:
        route = {k: [r for r in reviewed if records[r]["route"]["kind"] == k]
                 for k in ("euclid", "modified", "alternative")}
        if len(route["euclid"]) == len(reviewed):
            out.append("Every proof follows Euclid's argument, and each page notes where the "
                       "Lean departs from his sentences.")
        else:
            k = len(route["euclid"])
            parts = [f"{k} proof{'' if k == 1 else 's'} follow{'s' if k == 1 else ''} "
                     "Euclid's argument"]
            if route["modified"]:
                k = len(route["modified"])
                parts.append(f"{k} follow{'s' if k == 1 else ''} it with one step changed "
                             f"({links(route['modified'])})")
            if route["alternative"]:
                k = len(route["alternative"])
                parts.append(f"{k} {'argues' if k == 1 else 'argue'} differently "
                             f"({links(route['alternative'])})")
            out.append(and_list(parts) + "; each page says how.")
        overlap = [r for r in reviewed if "overlap" in records[r]]
        if overlap:
            out.append(overlap_sentences(overlap, facts, records, links, up))
    if postulate5 and len(proved) == count:
        out.append(postulate5_sentence(book, facts, proved))
    return " ".join(out)


def index(book, count, titles, facts, records):
    start = f"Start with the [{in_words(front_sections(book))}](front.md)."
    if (ROOT / "docs" / "reports" / f"gaps-book-{book}.md").exists():
        start += (" What Euclid takes for granted along the way is gathered in "
                  f"[a catalogue](../../docs/reports/gaps-book-{book}.md).")
    # The key names only the marks the table uses: a finished book shows ✅ alone.
    used = {facts.get(f"{book}.{n}", {}).get("status", "sketched") for n in range(1, count + 1)}
    legend = " · ".join(f"{STATUS_SHORT[s]} {t}" for s, t in (
        ("proved", "proved"),
        ("proved-pending", "proved, citing propositions still to be proved"),
        ("sketched", "stated")) if s in used)
    summary = book_summary(book, facts, records, lambda r: f"{int(r.split('.')[1]):02d}.md",
                           up="../../")
    out = [GENERATED, f"# Book {book}", "", summary, "",
           f"Key to the table: {legend}. The Lean statement is *whole*, as Euclid states it; "
           "*restricted*, with hypotheses that leave out cases his words admit; or *in "
           "part*, leaving a clause to his words. Each page says how.", ""]
    intro = book_intro(book)
    if intro:
        out += [intro, "", "## The propositions", ""]
    out += [start, "",
            "Books and papers to read alongside, from Proclus to Lean, are gathered by theme "
            "in [the reading list](../../docs/reading.md).", "",
            "| | Proposition | Lean statement | |", "|---|---|---|---|"]
    for n in range(1, count + 1):
        st = facts.get(f"{book}.{n}", {}).get("status", "sketched")
        record = records.get(f"{book}.{n}")
        scope = SCOPE_WORD[record["statement"]["scope"]] if record else ""
        _, enunciation, _ = heath.read(book, n)
        short = enunciation if len(enunciation) < 110 else enunciation[:107].rsplit(" ", 1)[0] + "…"
        out.append(f"| {STATUS_SHORT[st]} | [{book}.{n}]({n:02d}.md) **{titles[n]}** | {scope} "
                   f"| {short} |")
    return "\n".join(out) + "\n"


