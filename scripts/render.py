def load_facts():
    path = ROOT / "facts.json"
    if not path.exists():
        return {}
    return {p["ref"]: p for p in json.loads(path.read_text())["propositions"]}


def load_axiom_docs():
    """name -> (first sentence of docstring, path, line) for every axiom."""
    docs = {}
    pattern = re.compile(r"/--((?:(?!-/).)*?)-/\s*axiom\s+([^\s({]+)", re.S)
    for path in sorted((ROOT / "Elements" / "Foundations").rglob("*.lean")):
        src = path.read_text()
        # facts.json names an axiom by its namespace below `Elements`, e.g.
        # `Tacit.circles_meet` or, for a Euclidean-only rule, `Tacit.Euclidean.…`.
        ns = re.search(r"^namespace Elements\.(\S+)", src, re.M)
        prefix = ns.group(1) + "." if ns else ""
        for m in pattern.finditer(src):
            doc = " ".join(m.group(1).split())
            line = src[: m.start(2)].count("\n") + 1
            docs[prefix + m.group(2)] = (doc, path.relative_to(ROOT).as_posix(), line)
    return docs


def svg_desc(path):
    """The one-line caption kept in an SVG's <desc> element."""
    m = re.search(r"<desc>(.*?)</desc>", path.read_text(), re.S)
    return " ".join(m.group(1).split()) if m else ""


def lean_body(path):
    """The part of a proposition file worth showing: from `open Tacit` to the end."""
    src = path.read_text()
    start = src.find("open Tacit")
    end = src.rfind("end Elements.Book")
    body = src[start + len("open Tacit"):end] if start >= 0 else src
    return body.strip("\n")


def axiom_kind(path: str) -> str:
    if path.endswith("Tacit/Magnitudes.lean"):
        return "Laws of magnitude"
    if path.endswith(("Tacit/Constructions.lean", "Tacit/Diagram.lean")):
        return "Reading the figure"
    if path.endswith(("Tacit/Metric.lean", "Tacit/Transfer.lean")):
        return "Lengths, angles and areas"
    if path.endswith("Tacit/Superposition.lean"):
        return "Superposition"
    return "Other"


def roman_list(names, prefix):
    return ", ".join(n.replace(prefix, "") for n in sorted(names, key=lambda s: int(re.sub(r"\D", "", s) or 0)))


def definition_list(names, book):
    """Book I's definitions a proof rests on (`Definition15`). Definitions are numbered
    book by book, so outside Book I each keeps its book: "15" on a page of Book I, "I.15"
    on a page of Book II, whose own Definitions 1 and 2 are words, not assumptions."""
    nums = roman_list(names, "Definition")
    if book == "I" or not nums:
        return nums
    return ", ".join(f"I.{n}" for n in nums.split(", "))


def prop_key(ref):
    """Sort references by book, then by number: I.3 before I.10, and I.47 before II.4."""
    return heath.prop_key(ref)


def prop_link(ref, book):
    """A link to a proposition's page, from a page of `book`."""
    b, num = ref.split(".")
    where = "" if b == book else f"../{b}/"
    return f"[{ref}]({where}{int(num):02d}.md)"


def euclid_cites(paragraphs, book=None):
    """What Euclid gives in brackets, in four groups: propositions, postulates,
    definitions and common notions, each sorted by number (I.3 before I.10). On a page
    of `book`, that book's own definitions are written without it."""
    groups = {"props": [], "Post.": [], "Def.": [], "C.N.": []}
    for j in heath.justifications(paragraphs):
        kind, num = j.rsplit(" ", 1)
        if kind in ("Post.", "Def.", "C.N."):
            groups[kind].append(int(num))
        elif kind.endswith(" Def.") and kind.split(".")[0] == book:
            # "III. Def. 11" on a page of Book III is that book's own Definition 11.
            groups["Def."].append(int(num))
        elif kind.endswith(" Def."):
            # "I. Def. 15" in a later book: a definition of another book keeps its book.
            groups["Def."].append(f"{kind.split('.')[0]}.{num}")
        else:
            groups["props"].append(f"{kind}{num}")  # "I. 4", or "V. 9" in a later book
    groups["props"].sort(key=prop_key)
    for kind in ("Post.", "Def.", "C.N."):
        # The page's own book first (Def. 1, 2), then another's (Def. I.15).
        groups[kind].sort(key=lambda d: (0, d) if isinstance(d, int) else (1, prop_key(d)))
    return groups


def euclid_cites_text(groups, book):
    """Euclid's brackets for a page, grouped as Heath writes them: "I.3, I.4; Post. 1, 2"."""
    parts = [", ".join(prop_link(c, book) for c in groups["props"])]
    parts += [f"{kind} " + ", ".join(map(str, groups[kind]))
              for kind in ("Post.", "Def.", "C.N.") if groups[kind]]
    return "; ".join(x for x in parts if x)


def euclids_text(source):
    """The footer naming Heath's pages. The source comment starts with "Source:"."""
    source = re.sub(r"^Source:\s*", "", source)
    return f"<sub>Euclid's text: {source}</sub>"


# The Internet Archive scans of Heath's volumes: vol. 1 (Books I–II), vol. 2 (Books III–IX).
SCANS = {"1": "thirteenbookseu02heibgoog", "2": "thirteenbookseu00heibgoog"}


def heath_figure_note(source):
    """For a proposition whose lettered figure is still to be drawn: where Heath's own is,
    read from the source comment ("vol. 2 … figure on n18", "figures on n67 and n68")."""
    vol = re.search(r"vol\. (\d+)", source)
    leaves = re.search(r"figures? on (n\d+(?:(?:, | and )n\d+)*)", source)
    if not vol or not leaves or vol.group(1) not in SCANS:
        return "_Euclid's figure, with Heath's letters, is still to be drawn._"
    url = f"https://archive.org/details/{SCANS[vol.group(1)]}/page/"
    found = re.findall(r"n\d+", leaves.group(1))
    if len(found) == 1:
        where = f"[scan leaf {found[0]}]({url}{found[0]})"
    else:
        links = [f"[{leaf}]({url}{leaf})" for leaf in found]
        where = "scan leaves " + ", ".join(links[:-1]) + " and " + links[-1]
    if leaves.group(0).startswith("figures"):
        # Heath draws more than one figure (III.25, III.33, III.35, III.36).
        return ("_Euclid's figures, with Heath's letters, are still to be drawn; until then, "
                f"Heath's own are on {where}._")
    return ("_Euclid's figure, with Heath's letters, is still to be drawn; until then, "
            f"Heath's own is on {where}._")


