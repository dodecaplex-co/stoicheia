def front(book):
    raw = (ROOT / "heath" / book / "front.md").read_text()
    source = heath.HTML_COMMENT.match(raw.strip()).group(0)[4:-3].strip()
    text = heath.HTML_COMMENT.sub("", raw)
    out = [GENERATED, f"[Book {book}](index.md)", "",
           f"# Book {book}: Definitions, Postulates, Common Notions", "",
           "Euclid's words on the left, the Lean that stands for them on the right. "
           "Words with no Lean partner are never used in a proof.", ""]
    section = None
    for line in text.splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
            out += ["", f"## {section}", "", "| | Euclid | Lean |", "|---|---|---|"]
        elif re.match(r"^\d+\. ", line) and section:
            num, rest = line.split(". ", 1)
            lean = FRONT_LEAN_I.get(section, {}).get(int(num), "")
            out.append(f"| {num} | {rest} | {lean} |")
        elif line.strip() and section and not line.startswith("#"):
            out += ["", f"_{line.strip()}_", ""] if not out[-1].startswith("|") else \
                ["", f"_{line.strip()}_", "", "| | Euclid | Lean |", "|---|---|---|"]
    out += ["", "---", "", f"<sub>Euclid's text: {source}</sub>", ""]
    return "\n".join(out)


def certificate(facts, docs):
    out = [GENERATED, "# Certificate", "",
           "Everything on this page is computed from the Lean proofs themselves by "
           "[`Certificate/Facts.lean`](Certificate/Facts.lean): Lean's `#print axioms` tells us "
           "exactly which postulates, definitions and tacit assumptions each proof rests on. "
           "Nothing here is typed in by hand.", ""]
    for book, (count, titles) in BOOKS.items():
        props = [facts.get(f"{book}.{n}") for n in range(1, count + 1)]
        proved = [p for p in props if p and p["status"] == "proved"]
        out += [f"## Book {book}", "",
                f"**{len(proved)} of {count} propositions proved.**", ""]
        no_p5 = [p["ref"] for p in proved if "Postulate5" not in p["axioms"]]
        with_p5 = [p["ref"] for p in proved if "Postulate5" in p["axioms"]]
        sup = [p["ref"] for p in props if p and "Tacit.superposition" in p["direct_axioms"]]
        out += ["What the proofs show so far:", ""]
        out.append(f"- **Postulate 5**: {len(no_p5)} proved proposition(s) do without it"
                   + (f"; {len(with_p5)} use it, the first being {with_p5[0]}." if with_p5 else
                      ". None of the proved propositions uses it yet.")
                   + " Euclid holds it back until I.29.")
        out.append("- **Superposition** is used directly by: " + (", ".join(sup) or "none yet")
                   + ". Only I.4 and I.8 are allowed to.")
        out += ["", "| | Prop | Cites | Postulates | Definitions | C.N. | Tacit |",
                "|---|---|---|---|---|---|---|"]
        for n, p in enumerate(props, 1):
            ref = f"{book}.{n}"
            link = f"[{ref}](book/{book}/{n:02d}.md)"
            if not p or p["status"] == "sketched":
                out.append(f"| 🚧 | {link} | | | | | |")
                continue
            ax = p["axioms"]
            posts = roman_list([a for a in ax if a.startswith("Postulate")], "Postulate")
            defs = roman_list([a for a in ax if a.startswith("Definition")], "Definition")
            cns = ", ".join(c.replace("C.N. ", "") for c in sorted(set(p["common_notions"])))
            tacit = len([a for a in ax if a.startswith("Tacit.")])
            out.append(f"| {STATUS_SHORT[p['status']]} | {link} | {', '.join(p['cites'])} | "
                       f"{posts} | {defs} | {cns} | {tacit} |")
        out.append("")
    lean_version = next(iter(facts.values()), {}).get("lean_version", "")
    out += ["The Common Notions are theorems in Lean (see "
            "[`CommonNotions.lean`](Elements/Foundations/CommonNotions.lean)), so they are "
            "counted where a proof cites them by name. Lean's own logical foundations "
            "(`propext`, `Classical.choice`, `Quot.sound`) are not Euclid's assumptions and "
            "are left out.", ""]
    return "\n".join(out)


def graph(facts):
    out = [GENERATED, "# Who uses whom", "",
           "Each arrow runs from a proposition to one that cites it, following Euclid's own "
           "bracketed references in Heath's translation. Green: proved in Lean; grey: sketched.",
           ""]
    for book, (count, titles) in BOOKS.items():
        out += [f"## Book {book}", "", "```mermaid", "graph TD"]
        for n in range(1, count + 1):
            out.append(f'  {book}{n}["{book}.{n}"]')
        for n in range(1, count + 1):
            _, _, proof = heath.read(book, n)
            for c in sorted(heath.citations(proof), key=lambda c: (c.split(".")[0], int(c.split(".")[1]))):
                b, m = c.split(".")
                if b == book and int(m) != n:
                    out.append(f"  {book}{m} --> {book}{n}")
        out.append("  classDef proved fill:#d4edda,stroke:#2e7d32,color:#1b5e20")
        out.append("  classDef sketched fill:#eeeeee,stroke:#9e9e9e,color:#424242")
        proved = [f"{book}{n}" for n in range(1, count + 1)
                  if facts.get(f"{book}.{n}", {}).get("status") in ("proved", "proved-pending")]
        sketched = [f"{book}{n}" for n in range(1, count + 1) if f"{book}{n}" not in proved]
        if proved:
            out.append(f"  class {','.join(proved)} proved")
        if sketched:
            out.append(f"  class {','.join(sketched)} sketched")
        out += ["```", ""]
        for n in range(1, count + 1):
            out.append(f"- [{book}.{n}](book/{book}/{n:02d}.md): {titles[n]}")
        out.append("")
    return "\n".join(out)


def main() -> None:
    facts = load_facts()
    docs = load_axiom_docs()
    for book, (count, titles) in BOOKS.items():
        out_dir = ROOT / "book" / book
        out_dir.mkdir(parents=True, exist_ok=True)
        for n in range(1, count + 1):
            (out_dir / f"{n:02d}.md").write_text(page(book, n, count, titles, facts, docs))
        (out_dir / "index.md").write_text(index(book, count, titles, facts))
        (out_dir / "front.md").write_text(front(book))
    (ROOT / "CERTIFICATE.md").write_text(certificate(facts, docs))
    (ROOT / "GRAPH.md").write_text(graph(facts))
    print("rendered book pages, CERTIFICATE.md and GRAPH.md")


if __name__ == "__main__":
    main()
